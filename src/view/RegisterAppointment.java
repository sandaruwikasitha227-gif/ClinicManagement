    private void calculateTotal() {

    try {

        double consultation =
                Double.parseDouble(
                        txtConsultationFee.getText().trim()
                );

        double treatment =
                Double.parseDouble(
                        txtTreatmentCost.getText().trim()
                );

        double total = consultation + treatment;

        txtTotal.setText(
                String.format("%.2f", total)
        );

    } catch (NumberFormatException e) {

        txtTotal.setText("0.00");
    }
}
