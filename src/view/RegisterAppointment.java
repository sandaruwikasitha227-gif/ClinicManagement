    private void cmbTreatmentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbTreatmentActionPerformed
        // TODO add your handling code here:
        if (cmbTreatment.getSelectedItem() == null) {
        return;
    }

    String selected =
            cmbTreatment.getSelectedItem().toString();

    try {

        String[] parts = selected.split(" - ");

        double cost = Double.parseDouble(
                parts[parts.length - 1]
                        .replace("Rs.", "")
                        .trim()
        );

        txtTreatmentCost.setText(
                String.format("%.2f", cost)
        );

        calculateTotal();

    } catch (Exception e) {

        txtTreatmentCost.setText("0.00");
        txtTotal.setText("0.00");
    }
    }//GEN-LAST:event_cmbTreatmentActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (cmbPatient.getSelectedItem() == null
            || cmbDentist.getSelectedItem() == null
            || cmbTreatment.getSelectedItem() == null) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select patient, dentist and treatment.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String date =
            txtAppointmentDate.getText().trim();

    String time =
            txtAppointmentTime.getText().trim();

    if (date.isEmpty() || time.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter appointment date and time.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    try {

        String patientText =
                cmbPatient.getSelectedItem().toString();

        String dentistText =
                cmbDentist.getSelectedItem().toString();

        String treatmentText =
                cmbTreatment.getSelectedItem().toString();

        int patientId = Integer.parseInt(
                patientText.split(" - ")[0]
        );

        int dentistId = Integer.parseInt(
                dentistText.split(" - ")[0]
        );

        int treatmentId = Integer.parseInt(
                treatmentText.split(" - ")[0]
        );

        // Validate date
        java.sql.Date.valueOf(date);

        // Validate time
        java.sql.Time.valueOf(time + ":00");

        dao.AppointmentDAO appointmentDAO =
                new dao.AppointmentDAO();

        // Prevent double booking
        if (!appointmentDAO.isDentistAvailable(
                dentistId,
                date,
                time + ":00")) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "This dentist already has an appointment "
                    + "at the selected date and time.\n\n"
                    + "Please select another time.",
                    "Double Booking",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        double consultationFee =
                Double.parseDouble(
                        txtConsultationFee.getText().trim()
                );

        double treatmentCost =
                Double.parseDouble(
                        txtTreatmentCost.getText().trim()
                );

        double total =
                consultationFee + treatmentCost;

        model.Appointment appointment =
                new model.Appointment();

        appointment.setAppointmentNumber(
                txtAppointmentNumber.getText()
        );

        appointment.setPatientId(patientId);
        appointment.setDentistId(dentistId);
        appointment.setTreatmentId(treatmentId);
        appointment.setAppointmentDate(date);
        appointment.setAppointmentTime(time + ":00");
        appointment.setStatus("CONFIRMED");
        appointment.setConsultationFee(consultationFee);
        appointment.setTotalAmount(total);

        boolean success =
                appointmentDAO.addAppointment(appointment);

        if (success) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Appointment registered successfully!\n\n"
                    + "Appointment No: "
                    + appointment.getAppointmentNumber()
                    + "\nTotal: Rs. "
                    + String.format("%.2f", total),
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            clearAppointmentForm();

            loadAppointmentNumber();

        } else {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to save appointment.",
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (IllegalArgumentException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Invalid date or time format.\n\n"
                + "Date: YYYY-MM-DD\n"
                + "Time: HH:MM",
                "Invalid Input",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage(),
                "System Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSaveActionPerformed

