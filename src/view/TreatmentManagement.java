    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
            String name =
            txtTreatmentName.getText().trim();

    String costText =
            txtTreatmentCost.getText().trim();

    String status =
            cmbStatus.getSelectedItem().toString();

    if (name.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the treatment name.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        txtTreatmentName.requestFocus();
        return;
    }

    if (costText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the treatment cost.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        txtTreatmentCost.requestFocus();
        return;
    }

    double cost;

    try {

        cost = Double.parseDouble(costText);

        if (cost < 0) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter a valid treatment cost.",
                "Invalid Cost",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        txtTreatmentCost.requestFocus();
        return;
    }

    model.Treatment treatment =
            new model.Treatment();

    treatment.setTreatmentName(name);
    treatment.setTreatmentCost(cost);
    treatment.setStatus(status);

    dao.TreatmentDAO treatmentDAO =
            new dao.TreatmentDAO();

    if (treatmentDAO.addTreatment(treatment)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Treatment added successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        clearForm();
        loadTreatments();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to add treatment.",
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSaveActionPerformed

