    private void tblTreatmentsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTreatmentsMouseClicked
        // TODO add your handling code here:
            int row =
            tblTreatments.getSelectedRow();

    if (row >= 0) {

        txtTreatmentName.setText(
                tblTreatments
                        .getValueAt(row, 1)
                        .toString()
        );

        String cost =
                tblTreatments
                        .getValueAt(row, 2)
                        .toString()
                        .replace("Rs.", "")
                        .trim();

        txtTreatmentCost.setText(cost);

        cmbStatus.setSelectedItem(
                tblTreatments
                        .getValueAt(row, 3)
                        .toString()
        );
    }
    }//GEN-LAST:event_tblTreatmentsMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
            int row =
            tblTreatments.getSelectedRow();

    if (row == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a treatment from the table.",
                "Selection Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int treatmentId =
            Integer.parseInt(
                    tblTreatments
                            .getValueAt(row, 0)
                            .toString()
            );

    String name =
            txtTreatmentName.getText().trim();

    String costText =
            txtTreatmentCost.getText().trim();

    if (name.isEmpty() || costText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please complete all required fields.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    double cost;

    try {

        cost = Double.parseDouble(costText);

        if (cost < 0) {
            throw new NumberFormatException();
        }

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter a valid treatment cost.",
                "Invalid Cost",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    String status =
            cmbStatus.getSelectedItem().toString();

    model.Treatment treatment =
            new model.Treatment();

    treatment.setTreatmentId(treatmentId);
    treatment.setTreatmentName(name);
    treatment.setTreatmentCost(cost);
    treatment.setStatus(status);

    dao.TreatmentDAO treatmentDAO =
            new dao.TreatmentDAO();

    if (treatmentDAO.updateTreatment(treatment)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Treatment updated successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        clearForm();
        loadTreatments();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to update treatment.",
                "Database Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

