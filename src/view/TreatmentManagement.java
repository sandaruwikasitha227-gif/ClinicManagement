    private void loadTreatments() {

    dao.TreatmentDAO treatmentDAO =
            new dao.TreatmentDAO();

    java.util.List<model.Treatment> treatments =
            treatmentDAO.getAllTreatmentsList();

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel)
                    tblTreatments.getModel();

    model.setRowCount(0);

    for (model.Treatment treatment : treatments) {

        model.addRow(new Object[]{
            treatment.getTreatmentId(),
            treatment.getTreatmentName(),
            String.format(
                    "Rs. %.2f",
                    treatment.getTreatmentCost()
            ),
            treatment.getStatus()
        });
    }
}
    
