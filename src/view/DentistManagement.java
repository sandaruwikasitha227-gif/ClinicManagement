    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
            String name =
            txtDentistName.getText().trim();

    String specialization =
            txtSpecialization.getText().trim();

    String status =
            cmbStatus.getSelectedItem().toString();

    if (name.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please enter the dentist name.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        txtDentistName.requestFocus();
        return;
    }

    model.Dentist dentist =
            new model.Dentist();

    dentist.setDentistName(name);
    dentist.setSpecialization(specialization);
    dentist.setStatus(status);

    dao.DentistDAO dentistDAO =
            new dao.DentistDAO();

    if (dentistDAO.addDentist(dentist)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Dentist added successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        clearForm();
        loadDentists();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to add dentist.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnSaveActionPerformed

