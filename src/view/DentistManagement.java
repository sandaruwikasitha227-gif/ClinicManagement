    private void tblDentistsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblDentistsMouseClicked
        // TODO add your handling code here:
            int row = tblDentists.getSelectedRow();

    if (row >= 0) {

        txtDentistName.setText(
                tblDentists.getValueAt(row, 1).toString()
        );

        txtSpecialization.setText(
                tblDentists.getValueAt(row, 2).toString()
        );

        cmbStatus.setSelectedItem(
                tblDentists.getValueAt(row, 3).toString()
        );
    }
    }//GEN-LAST:event_tblDentistsMouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
            int row = tblDentists.getSelectedRow();

    if (row == -1) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a dentist from the table.",
                "Selection Required",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    int dentistId =
            Integer.parseInt(
                    tblDentists.getValueAt(row, 0).toString()
            );

    String name =
            txtDentistName.getText().trim();

    String specialization =
            txtSpecialization.getText().trim();

    String status =
            cmbStatus.getSelectedItem().toString();

    if (name.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Dentist name cannot be empty.",
                "Validation Error",
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    model.Dentist dentist =
            new model.Dentist();

    dentist.setDentistId(dentistId);
    dentist.setDentistName(name);
    dentist.setSpecialization(specialization);
    dentist.setStatus(status);

    dao.DentistDAO dentistDAO =
            new dao.DentistDAO();

    if (dentistDAO.updateDentist(dentist)) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Dentist updated successfully!",
                "Success",
                javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        clearForm();
        loadDentists();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to update dentist.",
                "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

